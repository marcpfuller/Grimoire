// --- findActivateMarker + buildActivateMarker ---

func TestBuildActivateMarker(t *testing.T) {
	marker := buildActivateMarker(42, 1000, "abc1234")
	assert.Contains(t, string(marker), "id=42")
	assert.Contains(t, string(marker), "start=1000")
	assert.Contains(t, string(marker), "sid=abc1234")

	// Round-trip: marker generated by buildActivateMarker must be parseable.
	_, _, params, found := findActivateMarker(marker)
	require.True(t, found, "round-trip parse failed")
	assert.Equal(t, int64(42), params.commandID)
	assert.Equal(t, int64(1000), params.startedAt)
	assert.Equal(t, "abc1234", params.shortID)
}

func TestFindActivateMarker(t *testing.T) {
	const (
		cmdID   int64 = 42
		start   int64 = 1000
		shortID       = "abc1234"
	)

	t.Run("no_marker", func(t *testing.T) {
		_, _, _, found := findActivateMarker([]byte("just prompt output"))
		assert.False(t, found)
	})

	t.Run("incomplete_marker_no_st", func(t *testing.T) {
		// Marker spans a buffer boundary — no ST found.
		_, _, _, found := findActivateMarker([]byte("\x1b]133;C;id=42;start=1000;sid=abc1234"))
		assert.False(t, found)
	})

	t.Run("invalid_params_missing_id", func(t *testing.T) {
		_, _, _, found := findActivateMarker([]byte("\x1b]133;C;start=1000;sid=abc1234\x1b\\"))
		assert.False(t, found, "id=0 is invalid")
	})

	t.Run("invalid_params_missing_start", func(t *testing.T) {
		_, _, _, found := findActivateMarker([]byte("\x1b]133;C;id=42;sid=abc1234\x1b\\"))
		assert.False(t, found, "start=0 is invalid")
	})

	t.Run("invalid_params_missing_sid", func(t *testing.T) {
		_, _, _, found := findActivateMarker([]byte("\x1b]133;C;id=42;start=1000\x1b\\"))
		assert.False(t, found, "empty sid is invalid")
	})

	t.Run("valid_marker_at_start", func(t *testing.T) {
		marker := buildActivateMarker(cmdID, start, shortID)
		input := append(marker, []byte("cmd output")...)
		before, after, params, found := findActivateMarker(input)
		require.True(t, found)
		assert.Equal(t, 0, before)
		assert.Equal(t, []byte("cmd output"), input[after:])
		assert.Equal(t, cmdID, params.commandID)
		assert.Equal(t, start, params.startedAt)
		assert.Equal(t, shortID, params.shortID)
	})

	t.Run("valid_marker_in_middle", func(t *testing.T) {
		marker := buildActivateMarker(cmdID, start, shortID)
		input := append(append([]byte("prompt"), marker...), []byte("cmd output")...)
		before, after, params, found := findActivateMarker(input)
		require.True(t, found)
		assert.Equal(t, []byte("prompt"), input[:before])
		assert.Equal(t, []byte("cmd output"), input[after:])
		assert.Equal(t, cmdID, params.commandID)
	})

	t.Run("valid_marker_at_end_nothing_after", func(t *testing.T) {
		marker := buildActivateMarker(cmdID, start, shortID)
		input := append([]byte("prompt"), marker...)
		before, after, _, found := findActivateMarker(input)
		require.True(t, found)
		assert.Equal(t, []byte("prompt"), input[:before])
		assert.Empty(t, input[after:])
	})
}

// --- maybeStore ---

// mockStore captures AppendOutputChunk calls for inspection.
type mockStore struct {
	db.Store
	chunks []*db.OutputChunk
}

func (m *mockStore) AppendOutputChunk(_ context.Context, chunk *db.OutputChunk) error {
	c := &db.OutputChunk{
		CommandID: chunk.CommandID,
		OffsetMs:  chunk.OffsetMs,
		Data:      append([]byte(nil), chunk.Data...),
	}
	m.chunks = append(m.chunks, c)
	return nil
}

func TestStoreChunk(t *testing.T) {
	t.Run("stores_chunk", func(t *testing.T) {
		ms := &mockStore{}
		startedAt := time.Now().UnixMilli()
		sess := &Session{store: ms}

		sess.storeChunk(context.Background(), []byte("hello"), 99, startedAt, "abc1234")

		require.Len(t, ms.chunks, 1)
		assert.Equal(t, int64(99), ms.chunks[0].CommandID)
		assert.Equal(t, []byte("hello"), ms.chunks[0].Data)
		assert.GreaterOrEqual(t, ms.chunks[0].OffsetMs, int64(0))
	})

	t.Run("offset_ms_non_negative_even_if_clock_skew", func(t *testing.T) {
		ms := &mockStore{}
		futureStart := time.Now().UnixMilli() + 9999 // startedAt in the future
		sess := &Session{store: ms}

		sess.storeChunk(context.Background(), []byte("data"), 1, futureStart, "abc1234")

		require.Len(t, ms.chunks, 1)
		assert.Zero(t, ms.chunks[0].OffsetMs, "offset_ms must not be negative")
	})

	t.Run("data_is_copied_not_aliased", func(t *testing.T) {
		ms := &mockStore{}
		sess := &Session{store: ms}
		startedAt := time.Now().UnixMilli()

		buf := []byte("original")
		sess.storeChunk(context.Background(), buf, 1, startedAt, "abc1234")
		buf[0] = 'X' // mutate original

		require.Len(t, ms.chunks, 1)
		assert.Equal(t, []byte("original"), ms.chunks[0].Data, "stored data must be a copy")
	})
}

// --- readLoop integration ---

func TestReadLoop(t *testing.T) {
	t.Run("passthrough_only_in_idle_state", func(t *testing.T) {
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}

		sess.readLoop(context.Background(), bytes.NewReader([]byte("prompt text")))

		assert.Equal(t, "prompt text", out.String(), "idle bytes must reach out")
		assert.Empty(t, ms.chunks, "idle state: nothing stored")
	})

	t.Run("capturing_state_writes_to_out_and_store", func(t *testing.T) {
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}
		sess.state.activate(5, time.Now().UnixMilli(), "abc1234")

		sess.readLoop(context.Background(), bytes.NewReader([]byte("command output bytes")))

		assert.Equal(t, "command output bytes", out.String(), "captured bytes must still reach out")
		require.NotEmpty(t, ms.chunks)
		var stored []byte
		for _, c := range ms.chunks {
			stored = append(stored, c.Data...)
		}
		assert.Equal(t, []byte("command output bytes"), stored)
	})

	t.Run("activate_marker_activates_and_stores_after", func(t *testing.T) {
		// Activate marker: bytes before → passthrough only; bytes after → out AND stored.
		// Marker bytes themselves must NOT appear in out.
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}

		marker := buildActivateMarker(42, time.Now().UnixMilli(), "abc1234")
		payload := append(append([]byte("prompt"), marker...), []byte("ls output")...)
		sess.readLoop(context.Background(), bytes.NewReader(payload))

		assert.Equal(t, "promptls output", out.String(), "marker bytes must be stripped")
		require.NotEmpty(t, ms.chunks, "bytes after activate marker must be stored")
		var stored []byte
		for _, c := range ms.chunks {
			stored = append(stored, c.Data...)
		}
		assert.Equal(t, []byte("ls output"), stored)
		// State must be active after the marker.
		cmdID, _, _ := sess.state.snapshot()
		assert.Equal(t, int64(42), cmdID)
	})

	t.Run("activate_marker_mid_buffer_while_capturing_stores_before_under_old_id", func(t *testing.T) {
		// Edge case: activate marker arrives while already capturing (shouldn't
		// happen in normal flow where precmd fires between commands). Bytes before
		// the marker are stored under the outgoing commandID; bytes after under
		// the new commandID.
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}
		sess.state.activate(5, time.Now().UnixMilli(), "old0001")

		newStart := time.Now().UnixMilli()
		marker := buildActivateMarker(99, newStart, "new0099")
		payload := append(append([]byte("tail of cmd"), marker...), []byte("start of next")...)
		sess.readLoop(context.Background(), bytes.NewReader(payload))

		assert.Equal(t, "tail of cmdstart of next", out.String())
		require.Len(t, ms.chunks, 2, "two store calls: one for tail, one for new output")
		assert.Equal(t, int64(5), ms.chunks[0].CommandID, "tail stored under old ID")
		assert.Equal(t, []byte("tail of cmd"), ms.chunks[0].Data)
		assert.Equal(t, int64(99), ms.chunks[1].CommandID, "new output stored under new ID")
		assert.Equal(t, []byte("start of next"), ms.chunks[1].Data)
	})

	t.Run("deactivate_marker_clears_state_and_stores_before", func(t *testing.T) {
		// Deactivate marker: bytes before (tail of command) stored; state cleared;
		// bytes after (next prompt) passthrough only. Marker bytes stripped.
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}
		sess.state.activate(7, time.Now().UnixMilli(), "fin0007")

		payload := append(append([]byte("tail output"), deactivateMarker...), []byte("prompt$ ")...)
		sess.readLoop(context.Background(), bytes.NewReader(payload))

		assert.Equal(t, "tail outputprompt$ ", out.String(), "deactivate marker bytes stripped")
		require.NotEmpty(t, ms.chunks, "tail bytes before deactivate must be stored")
		var stored []byte
		for _, c := range ms.chunks {
			stored = append(stored, c.Data...)
		}
		assert.Equal(t, []byte("tail output"), stored)
		// State must be idle after deactivate.
		cmdID, _, _ := sess.state.snapshot()
		assert.Zero(t, cmdID)
	})

	t.Run("deactivate_marker_in_idle_state_noop", func(t *testing.T) {
		// Deactivate marker in idle state: nothing stored, state stays idle.
		ms := &mockStore{}
		var out bytes.Buffer
		sess := &Session{store: ms, out: &out}

		payload := append(append([]byte("before"), deactivateMarker...), []byte("after")...)
		sess.readLoop(context.Background(), bytes.NewReader(payload))

		assert.Equal(t, "beforeafter", out.String())
		assert.Empty(t, ms.chunks)
	})
}
